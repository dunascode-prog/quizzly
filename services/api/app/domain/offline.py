"""What "Save for offline" downloads for a course (FR-OFF-03, DESIGN.md screen 28).

The manifest lists every ready outline, every explanation already written for those topics (any
style, current prompt version) and the student's own ready quizzes, each with its size, so the app
can show the download size first and then fetch them one by one into its offline cache. Original
files are never included, and nothing is generated by downloading.
"""

from uuid import UUID

from psycopg import AsyncConnection

from app.rag.explain import PROMPT_VERSION

OVERHEAD = 400  # JSON keys and the rest of each response, roughly


async def manifest(conn: AsyncConnection, user_id: UUID, course_id: UUID) -> dict | None:
    """None when the course is neither the student's nor shared with them."""
    visible = await (
        await conn.execute(
            """
            select exists (select 1 from courses where id = %(c)s and user_id = %(u)s)
                or exists (select 1 from course_members m
                           join course_shares s on s.id = m.share_id and s.status = 'active'
                           where s.course_id = %(c)s and m.user_id = %(u)s
                             and m.status = 'active') as ok
            """,
            {"c": course_id, "u": user_id},
        )
    ).fetchone()
    if not visible["ok"]:
        return None
    params = {"c": course_id, "u": user_id, "v": PROMPT_VERSION, "o": OVERHEAD}
    documents = await (
        await conn.execute(
            """
            select d.id, d.title,
                   %(o)s + coalesce((select sum(octet_length(t.title)
                                            + coalesce(octet_length(t.summary), 0))
                                     from topics t where t.source_file_id = d.source_file_id), 0)
                     as bytes
            from documents d
            where d.course_id = %(c)s and d.status = 'ready' and d.deleted_at is null
              and d.kind = 'notes' and d.id in (select readable_documents(%(u)s))
            order by d.created_at
            """,
            params,
        )
    ).fetchall()
    ids = [d["id"] for d in documents]
    explanations = await (
        await conn.execute(
            """
            select distinct on (e.id) d.id as document_id, e.topic_id, e.style::text as style,
                   %(o)s + octet_length(e.content_md) as bytes
            from explanations e
            join topics t on t.id = e.topic_id and t.parent_id is null
            join documents d on d.source_file_id = e.source_file_id
            where d.id = any(%(ids)s) and e.status = 'ready' and e.prompt_version = %(v)s
              and e.content_md is not null
            order by e.id, d.created_at
            """,
            params | {"ids": ids},
        )
    ).fetchall()
    quizzes = await (
        await conn.execute(
            """
            select z.id, z.document_id, s.generated_count as questions,
                   %(o)s + coalesce((select sum(octet_length(q.stem) + octet_length(q.answer::text)
                                            + octet_length(q.explanation)
                                            + coalesce(octet_length(q.options::text), 0)
                                            + coalesce(octet_length(q.rubric::text), 0) + 120)
                                     from questions q where q.question_set_id = s.id
                                       and not q.hidden), 0) as bytes
            from quizzes z join question_sets s on s.id = z.question_set_id
            where z.user_id = %(u)s and z.document_id = any(%(ids)s) and z.kind <> 'daily5'
              and s.status = 'ready'
            order by z.created_at desc
            """,
            params | {"ids": ids},
        )
    ).fetchall()
    rows = [*documents, *explanations, *quizzes]
    return {
        "course_id": course_id,
        "documents": documents,
        "explanations": explanations,
        "quizzes": quizzes,
        "bytes": sum(int(r["bytes"]) for r in rows),
    }
