// Builds src/components/katex-css.ts: KaTeX's stylesheet with its fonts inlined as woff2 data
// URIs, so formulas render with no network at all (FR-SEC-16). Re-run after upgrading katex:
//   node scripts/build-katex-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const dist = dirname(require.resolve('katex/dist/katex.min.css'));
const version = JSON.parse(readFileSync(join(dist, '..', 'package.json'), 'utf8')).version;
let css = readFileSync(join(dist, 'katex.min.css'), 'utf8');

// Each @font-face lists woff2, woff and ttf; keep only woff2, inlined.
css = css.replace(/src:url\(fonts\/([^)]+?)\.woff2\) format\("woff2"\)[^;}]*/g, (_, name) => {
  const data = readFileSync(join(dist, 'fonts', `${name}.woff2`)).toString('base64');
  return `src:url(data:font/woff2;base64,${data}) format("woff2")`;
});
if (/url\(fonts\//.test(css)) throw new Error('a font reference was not inlined');

writeFileSync(
  'src/components/katex-css.ts',
  `// Generated by scripts/build-katex-css.mjs from katex ${version}. Do not edit.\n` +
    `export const KATEX_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`katex ${version}: ${Math.round(css.length / 1024)} KB of CSS with inlined fonts`);
